# Função print() é utilizada para exibir mensagens na tela.
# \r\n é utilizado para quebrar a linha e exibir o próximo conteúdo em uma nova linha. CRLF
# \n é utilizado para quebrar a linha e exibir o próximo conteúdo em uma nova linha. LF
# Argumento nomeado sep é utilizado para definir o separador entre os valores exibidos na tela.
# Argumento nomeado end é utilizado para definir o conteúdo a ser exibido no final da linha.
print(12, 34 ,1011, sep="-", end="\r\n")
print(56, 78, sep='-', end='\n')
print(9, 10, sep='-')